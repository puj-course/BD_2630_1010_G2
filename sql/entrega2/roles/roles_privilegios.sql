GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.EDICION_MUNDIAL TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.ENTRADA TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.ESTADIO TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.ESTADISTICA_JUGADOR_PARTIDO TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.FASE TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.FEDERACION TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.GRUPO TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.INCIDENCIA TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.JUGADOR TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.PARTICIPACION_PARTIDO TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.PARTIDO TO ROL_ADMIN_TORNEO;
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.SELECCION TO ROL_ADMIN_TORNEO;
GRANT SELECT ON IS101004.AUDITORIA_EVENTO TO ROL_ADMIN_TORNEO;


