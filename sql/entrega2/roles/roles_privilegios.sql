-- Entrega 2 - Semana 4: Roles y privilegios
--
-- Roles:
--   ROL_ADMIN_TORNEO       -> Administrador del Torneo
--   ROL_ANALISTA_DEPORTIVO -> Analista Deportivo
--   ROL_AUDITOR            -> Auditor / Consulta
--
-- Asignación
--   Julian (is101002) -> administrador y también auditor
--   Pablo  (is101010) -> analista deportivo

-- 1. Crear los roles
CREATE ROLE ROL_ADMIN_TORNEO;
CREATE ROLE ROL_ANALISTA_DEPORTIVO;
CREATE ROLE ROL_AUDITOR;


-- 2. ADMINISTRADOR DEL TORNEO
-- Puede consultar, insertar, modificar y borrar en las tablas del torneo.
-- En AUDITORIA_EVENTO solo puede consultar (no debe poder borrar la bitácora).
GRANT SELECT, INSERT, UPDATE, DELETE ON IS101004.ACREDITACION_PRENSA TO ROL_ADMIN_TORNEO;
